/**
 * Sample catalogue. Garment measurements are in cm, per UK size, measured on the
 * finished garment: circumferences for bust/waist/hip, seam-to-seam for shoulder,
 * shoulder point to cuff for sleeve, high point shoulder (or waist, for skirts) to
 * hem for length, and crotch to hem for inseam.
 */

export const STANDARD_SIZES = ['XS', 'S', 'M', 'L', 'XL', 'XXL'] as const;

function sizes(m: Partial<Record<Zone, number[]>>, labels: readonly string[] = STANDARD_SIZES): GarmentSize[] {
  return labels.map((label, i) => ({
    label,
    measurements: Object.fromEntries(
      Object.entries(m).map(([zone, values]) => [zone, values![i]]),
    ) as Partial<Record<Zone, number>>,
  }));
}

